function preset(
	name: string,
	category: string,
	mode: GradientField["mode"],
	palette: string[],
	patch: Partial<GradientField> = {},
	description = "",
): GradientPreset {
	const layer = {
		...createLayer("radial"),
		id: "legacy-preview",
		color: palette[2],
		color2: palette[4],
		width: 240,
		height: 240,
		blur: 25,
	};
	return {
		id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
		name,
		category,
		description:
			description ||
			`${name} — a softly moving ${category.toLowerCase()} study.`,
		document: {
			version: 1,
			name,
			background: palette[0],
			grain: 9,
			aspectRatio: "16:10",
			layers: [layer],
			field: { ...fieldDefaults(mode), palette: [...palette], ...patch },
		},
	};
}
